export function isExcludedByReview(word: Pick<Word, 'id'>): boolean {
  return JAPANESE_REVIEW_FIXES[word.id]?.exclude === true;
}

export function applyJapaneseReviewFix<T extends Word>(word: T): T {
  const fix = JAPANESE_REVIEW_FIXES[word.id];
  if (!fix || fix.exclude) return word;
  return {
    ...word,
    ...(fix.original ? { original: fix.original } : {}),
    ...(fix.translation ? { translation: fix.translation } : {}),
    ...(fix.part_of_speech ? { part_of_speech: fix.part_of_speech } : {}),
    ...(fix.reading ? { transcription: `[${fix.reading} · ${kanaToRomaji(fix.reading)}]` } : {}),
  };
}

