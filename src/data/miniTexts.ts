import type { LearningLanguage } from '../types';

/**
 * Short texts (3–5 sentences) for reading practice. Every content word is
 * listed in `words`: `form` is how it is written in the text, `lemma` the
 * dictionary entry it belongs to (so the app knows whether it was studied).
 * A word without `lemma` is not in the dictionary and is only glossed.
 */
export interface MiniTextWord {
  form: string;
  lemma?: string;
  translation: string;
  /** Japanese: the reading of the form. */
  reading?: string;
}

export interface MiniTextSentence {
  original: string;
  translation: string;
  /** Japanese: the whole sentence in hiragana. */
  reading?: string;
}

export interface MiniText {
  id: string;
  language: LearningLanguage;
  level: 'A1' | 'A2';
  title: string;
  sentences: MiniTextSentence[];
  words: MiniTextWord[];
}

